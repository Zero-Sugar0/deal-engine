function professionExpansion(
  input: Omit<
    Partial<ProfessionProfile>,
    'id' | 'title' | 'category' | 'summary' | 'objective'
  > &
    Pick<
      ProfessionProfile,
      'id' | 'title' | 'category' | 'summary' | 'objective'
    >,
): ProfessionProfile {
  return ProfessionProfileSchema.parse({
    version: '1.0.0',
    aliases: [],
    routingPriority: 50,
    routingTerms: [],
    responsibilities: [],
    knowledgeAreas: [],
    operatingPatterns: [shared.evidence, shared.clarify, shared.handoff],
    communicationPatterns: [shared.plainLanguage],
    decisionPatterns: [shared.tradeoffs],
    failureModes: ['unsupported certainty', 'scope overreach'],
    requiredContext: ['role', 'goal', 'constraints'],
    escalationTriggers: ['low confidence', 'material risk', 'missing context'],
    safetyBoundaries: [
      'Do not claim credentials, licensure, examination, or actions that are not verified.',
      'Make uncertainty and source provenance visible for consequential claims.',
    ],
    sensitiveDataClasses: [],
    regulated: false,
    licenseRequiredFor: [],
    restrictedActions: [],
    approvalActions: [],
    source: 'system',
    ...input,
  });
}

