import {
  ProfessionProfileSchema,
  type ProfessionProfile,
  type ProfessionalPattern,
} from '@deal/core';

const pattern = (
  id: string,
  label: string,
  description: string,
  useWhen: string[] = [],
  avoidWhen: string[] = [],
): ProfessionalPattern => ({
  id,
  label,
  description,
  useWhen,
  avoidWhen,
});

const evidence = pattern(
  'evidence_first',
  'Evidence first',
  'Separate observed facts, current sources, assumptions, and recommendations.',
);
const clarify = pattern(
  'clarify_before_action',
  'Clarify before action',
  'Ask for the one missing fact that would materially change the guidance.',
);
const handoff = pattern(
  'safe_handoff',
  'Safe handoff',
  'State what is known, what is uncertain, and who should take over when the boundary is reached.',
);
const tradeoffs = pattern(
  'surface_tradeoffs',
  'Surface trade-offs',
  'Make cost, risk, reversibility, and effort visible before recommending a path.',
);
const consent = pattern(
  'consent_and_dignity',
  'Consent and dignity',
  'Respect the person’s choices, privacy, and pace without shame or pressure.',
);
const safetyFirst = pattern(
  'safety_first',
  'Safety first',
  'Lead with immediate danger, isolation, evacuation, or emergency steps when relevant.',
);
const practical = pattern(
  'practical_steps',
  'Practical steps',
  'Give short, ordered steps with quantities, timing, checks, and stop conditions.',
);
const currentSource = pattern(
  'current_source_only',
  'Current source only',
  'Use a current official or local source for changing rules, weather, warnings, and conditions.',
);

function lifeContext(
  input: Omit<
    Partial<ProfessionProfile>,
    'id' | 'title' | 'category' | 'summary' | 'objective'
  > &
    Pick<
      ProfessionProfile,
      'id' | 'title' | 'category' | 'summary' | 'objective'
    >,
): ProfessionProfile {
  return ProfessionProfileSchema.parse({
    version: '1.0.0',
    subjectType: 'life_context',
    aliases: [],
    routingPriority: 60,
    routingTerms: [],
    responsibilities: [],
    knowledgeAreas: [],
    operatingPatterns: [evidence, clarify, handoff],
    communicationPatterns: [practical],
    decisionPatterns: [tradeoffs],
    failureModes: ['unsupported certainty', 'missing local or species context'],
    requiredContext: ['goal', 'constraints'],
    escalationTriggers: ['low confidence', 'material risk', 'missing context'],
    safetyBoundaries: [
      'Do not present general guidance as a diagnosis, certification, or current official ruling.',
      'Make uncertainty and source provenance visible when conditions change.',
    ],
    sensitiveDataClasses: [],
    regulated: false,
    licenseRequiredFor: [],
    restrictedActions: [],
    approvalActions: [],
    source: 'system',
    ...input,
  });
}

